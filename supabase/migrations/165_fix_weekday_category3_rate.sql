-- プラスワン1の基本報酬「平日・算定3（3時間超5時間以下）」を、放デイ412（算定2と同じ 609単位・63H592）に直す。
--
-- 入力マニュアル（令和6年度改定対応版）では 算定1→411、算定2・3→412、算定4（5時間超・休業日のみ）→413。
-- 平日・算定3 だけが 413 の値（666単位・63H610）になっていて、休日・算定3（609単位・63H592）と食い違っていた。
-- 渡邊太志 9月 9/18（13:10〜16:30）が 57単位多く計算され、上限管理で他ソフトの総費用額と合わなかった。
UPDATE billing_basic_rates
SET unit_count = 609, billing_code = '63H592'
WHERE unit_id = 'c0000000-0000-0000-0000-000000000001'
  AND service_form_type = 1
  AND billing_category = 3
  AND unit_count = 666
  AND billing_code = '63H610';
