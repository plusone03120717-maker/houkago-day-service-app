-- 地域区分「その他」のコードを 23 にする（142 → 145 で20に戻したものを再変更）。
--
-- 電子請求受付システム（簡易入力）の事業所情報保守画面を確認したところ、
-- 地域区分は「その他」というラベルのドロップダウンで、番号はどこにも表示されない。
-- つまり「20」はアプリ側のコメントが唯一の出所で、国保連側に裏付けがなかった。
--
-- 一方、前システムが取込に成功したCSV（令和8年7月分）の明細書 基本情報レコードは、
-- 37人全員が項目10 = 23。この項目は中身のある唯一の定数で、様式第二の並び
-- （障害児氏名 → 地域区分 → 利用者負担上限月額①）ともCSVの並びが一致する。
--
-- 暫定値。簡易入力システムが書き出すCSVの同項目を見れば確定するので、
-- 確認が取れるまではこの値で運用する。

ALTER TABLE facilities ALTER COLUMN region_code SET DEFAULT '23';
UPDATE facilities SET region_code = '23' WHERE region_code = '20';

COMMENT ON COLUMN facilities.region_code IS
  '地域区分コード（2桁）。その他 = 23（取込成功済みCSVの実値にもとづく暫定値）';
